# ── Serialisation helpers ─────────────────────────────────────────────────────

def summarize_local_context(ctx):
    return {"my_position": ctx["my_position"], "neighborhood": ctx["neighborhood"]}


def make_serializable(obj):
    if isinstance(obj, set):                       return list(obj)
    elif isinstance(obj, Path):                    return str(obj)
    elif hasattr(obj, "tolist"):                   return obj.tolist()
    elif isinstance(obj, (np.bool_, np.integer)):  return int(obj)
    elif isinstance(obj, np.floating):             return float(obj)
    elif isinstance(obj, dict):
        return {k: make_serializable(v) for k, v in obj.items()}
    elif isinstance(obj, (list, tuple)):
        return [make_serializable(i) for i in obj]
    return obj


# ── Post-processing strategy derivation ──────────────────────────────────────
#
# Computed deterministically from the three logged fields.
# Never sent to or generated by the LLM — zero token cost.

def derive_strategy(
    target_group: str,
    institution: str,
    call_to_action: str,
) -> str:
    """
    Derive a strategic orientation label from three already-logged fields.

    Parameters
    ----------
    target_group   : "citizens" | "pillars" | "police" | "activists"
    institution    : institution type string (e.g. "Trade Unions") or "N/A"
    call_to_action : CallToActionType string (e.g. "boycott")

    Returns
    -------
    One of:
      solidarity_building       — activist → activist network formation
      citizen_mobilisation      — activist → citizens
      security_force_conversion — activist → police (CANVAS: 'appeal to humanity')
      economic_disruption       — boycott/strike → economic institutions
      regime_delegitimisation   — petition/civil_disobedience → legal/political pillars
      moral_witness             — vigil/hunger_strike/symbolic → moral/info pillars
      pillar_persuasion         — general presence near pillar (catch-all)
    """
    if target_group == "activists":
        return "solidarity_building"
    if target_group == "citizens":
        return "citizen_mobilisation"
    if target_group == "police":
        return "security_force_conversion"
    if target_group == "pillars":

        # Economic noncooperation
        ECONOMIC_TACTICS = {"boycott", "strike"}
        ECONOMIC_PILLARS = {"Business Community", "Trade Unions", "Civil Service"}

        # Legal/political pressure
        LEGAL_TACTICS    = {"petition", "civil_disobedience"}
        LEGAL_PILLARS    = {"Parliament", "Supreme Court"}

        # Moral witness
        MORAL_TACTICS    = {"hunger_strike"}
        MORAL_PILLARS    = {"Religious Institutions", "Professional Associations"}

        # Physical presence/visibility
        PHYSICAL_TACTICS = {"sit_in", "march"}
        PHYSICAL_PILLARS = {"Educational System", "Local Government",
                            "Independent Media", "State Media"}

        if call_to_action in ECONOMIC_TACTICS and institution in ECONOMIC_PILLARS:
            return "economic_disruption"
        if call_to_action in LEGAL_TACTICS and institution in LEGAL_PILLARS:
            return "regime_delegitimisation"
        if call_to_action in MORAL_TACTICS and institution in MORAL_PILLARS:
            return "moral_witness"
        if call_to_action in PHYSICAL_TACTICS and institution in PHYSICAL_PILLARS:
            return "physical_solidarity"
        return "pillar_persuasion"

    return "unknown"


# ── NVBaseAgent ───────────────────────────────────────────────────────────────

class NVBaseAgent(mesa.Agent):
    def __init__(self, unique_id, agent_type, model):
        super().__init__(unique_id, model)
        self.type      = agent_type
        self.is_alive  = True
        self.inProtest = False
        self.delayStart = self.model.random.randrange(self.model.const["delayStartMax"])

        self.is_Citizen  = (self.type.name == "CITIZEN")
        self.is_Activist = (self.type.name == "ACTIVIST")
        self.is_Police   = (self.type.name == "POLICE")
        self.is_Pillar   = (self.type.name == "PILLAR")

        self.jailTerm       = 0
        self.protestCounter = 0 if (self.is_Citizen or self.is_Activist) else float('nan')

    def get_visible_agents(self, radius=None):
        if radius is None:
            radius = self.model.const["vision"]
        W, H = self.model.grid.width, self.model.grid.height

        big_neighborhood = self.model.grid.get_neighbors(
            pos=self.pos, moore=True, include_center=False, radius=radius
        )

        def toroidal_adjust(x, y):
            dx = x - self.pos[0]; dy = y - self.pos[1]
            if dx >  W / 2: dx -= W
            elif dx < -W / 2: dx += W
            if dy >  H / 2: dy -= H
            elif dy < -H / 2: dy += H
            return (W / 2 + dx, H / 2 + dy)

        torus_adj = [toroidal_adjust(a.pos[0], a.pos[1]) for a in big_neighborhood]
        self_adj  = (W / 2, H / 2)
        dists     = [np.linalg.norm(np.array(self_adj) - np.array(ap)) for ap in torus_adj]
        return [big_neighborhood[i] for i, d in enumerate(dists) if d <= radius]

    def ruleM(self):
        """Default random movement — overridden by ActivistAgent."""
        W, H   = self.model.grid.width, self.model.grid.height
        vision = self.model.const["vision"]
        big    = self.model.grid.get_neighborhood(
            pos=self.pos, moore=True, include_center=False, radius=vision
        )
        big = [x for x in big if self.model.grid.is_cell_empty(x)]

        def toroidal_adjust(x, y):
            dx = x - self.pos[0]; dy = y - self.pos[1]
            if dx >  W / 2: dx -= W
            elif dx < -W / 2: dx += W
            if dy >  H / 2: dy -= H
            elif dy < -H / 2: dy += H
            return (W / 2 + dx, H / 2 + dy)

        torus_adj = [toroidal_adjust(x, y) for x, y in big]
        self_adj  = (W / 2, H / 2)
        dists     = [np.linalg.norm(np.array(self_adj) - np.array(ap)) for ap in torus_adj]
        available = [big[i] for i, d in enumerate(dists) if d <= vision]
        if available:
            self.model.grid.move_agent(self, self.model.random.choice(available))


# ── CitizenAgent ──────────────────────────────────────────────────────────────

class CitizenAgent(NVBaseAgent):
    def __init__(self, unique_id, agent_type, model):
        super().__init__(unique_id, agent_type, model)
        self.activeNV         = False
        self.inProtest        = False
        self.fickle           = self.model.random.random() < self.model.const["ficklePct"]
        self.immediateProtest = self.model.random.random() < self.model.const["PctImmedProtest"]

        self.k1  = 2.3
        k2       = 0.025 * 3
        a, b     = (0.5, 0.5)
        Ey       = np.exp(a + 0.5 * (b ** 2))
        logy     = a + b * self.model.random.normalvariate(a, b)
        y        = np.exp(logy)
        self.hardship   = np.exp(Ey - y) / (1 + np.exp(Ey - y))
        costA = 2*np.exp(k2*self.model.const["MaxJailTerm"]*y)   / (1 + np.exp(k2*self.model.const["MaxJailTerm"]*y))   - 1
        costB = 2*np.exp(k2*self.model.const["MaxJailTerm"]/y)   / (1 + np.exp(k2*self.model.const["MaxJailTerm"]/y))   - 1
        self.arrestCost = (costA**4 + costB**4) ** 0.25
        self.grievance  = self.hardship * (1 - self.model.governmentLegitimacy)
        self.grievanceLevel = None

    def ruleC(self):
        self.grievance = self.hardship * (1 - self.model.governmentLegitimacy)
        neighbor_agents = self.get_visible_agents()
        policeSum, activistSum, nvcSum, protestSum = (0, 0, 0, 0)
        for n in neighbor_agents:
            policeSum   += n.is_Police
            activistSum += (n.is_Activist and not n.jailTerm)
            nvcSum      += (n.is_Citizen and n.activeNV)
            protestSum  += n.inProtest

        ArrestProbability = 1 - np.exp(-self.k1 * (policeSum / (1 + nvcSum + activistSum)))
        PeerPressure      = min(0.5 * protestSum / self.model.const["peerPressureNum"], 1)
        NVChoice          = self.grievance * PeerPressure - ArrestProbability * self.arrestCost
        self.activeNV     = NVChoice > self.model.const["joinNVThresh"]

        if self.activeNV:
            self.model.logger.log_agent_event(
                self, event="active_nv", pos=self.pos,
                context={"NearbyProtesters": protestSum, "NearbyPolice": policeSum,
                         "NearbyActivists": activistSum, "NearbyActiveNV": nvcSum},
            )

    def ruleNV(self):
        neighbor_agents = self.get_visible_agents()
        nvcSum, activistSum = (0, 0)
        for neighbor in neighbor_agents:
            nvcSum += (neighbor.is_Citizen and neighbor.activeNV)
            activistSum += (neighbor.is_Activist and not neighbor.jailTerm)

        if (activistSum + nvcSum) >= self.model.const["nNVthreshold"]:
            self.inProtest      = True
            self.protestCounter = self.model.const["protestCycle"]
            self.model.logger.log_agent_event(
                self, event="protest_start", pos=self.pos,
                context={"NearbyActiveNV": activistSum + nvcSum},
            )

    def step(self):
        if not self.is_alive or self.model.schedule.steps < (self.delayStart + 1):
            return
        if self.protestCounter > 0:
            self.protestCounter -= 1
            if self.protestCounter <= (self.model.const["protestCycle"] - self.model.const["protestDuration"]):
                self.inProtest = False
                self.model.logger.log_agent_event(
                    self, event="rest_phase", pos=self.pos,
                    context={"StepsToEnd": self.protestCounter},
                )
        if self.jailTerm == 0:
            self.ruleM()
        doNVfirst = self.immediateProtest
        for NVfirst in [False, True]:
            if doNVfirst == NVfirst:
                if self.activeNV and not self.protestCounter:
                    self.ruleNV()
                if self.inProtest:
                    self.model.protestCount += 1
            else:
                if not self.jailTerm and not (self.activeNV and not self.fickle):
                    self.ruleC()
        if self.jailTerm > 0:
            self.jailTerm -= 1


# ── ActivistAgent ─────────────────────────────────────────────────────────────

class ActivistAgent(NVBaseAgent):
    def __init__(self, unique_id, agent_type, model):
        super().__init__(unique_id, agent_type, model)
        self.activeNV  = True
        self.inProtest = False

    # ── Direction helper ──────────────────────────────────────────────────────

    @staticmethod
    def _get_direction(from_pos, to_pos, width, height):
        dx = to_pos[1] - from_pos[1]
        dy = to_pos[0] - from_pos[0]
        if dx >  width  / 2: dx -= width
        elif dx < -width  / 2: dx += width
        if dy >  height / 2: dy -= height
        elif dy < -height / 2: dy += height
        if abs(dx) <= 1 and abs(dy) <= 1:
            return "adjacent"
        vertical   = "north" if dy < 0 else "south" if dy > 0 else ""
        horizontal = "east"  if dx > 0 else "west"  if dx < 0 else ""
        return f"{vertical}{horizontal}".strip() or "here"

    # ── Coordination classifier ───────────────────────────────────────────────

    @staticmethod
    def _classify_coordination(n_free: int) -> str:
        if n_free == 0: return "isolated"
        if n_free == 1: return "flanking"
        if n_free <= 3: return "coordinated"
        return "clustered"

    # ── Context builder ───────────────────────────────────────────────────────
    def parse_context_by_direction(self, available_spaces, pillar_info,
                                   police_info, activists_info, nv_citizen_info):
        """
        Build the directional context dict sent to the LLM.

        Pillar bucket format (observable pressure, no private threshold labels):
          "pillars": {
            "defected":       ["Trade Unions"],
            "stable":         ["State Television", "Central Bank"]
          }

        The LLM sees "Trade Unions is under pressure" derived from visible
        protest density — not "wavering" derived from a private threshold value.
        The institution name is always shown so the LLM can reason about which
        type of pillar to approach.
        """
        my_pos = self.pos
        W = self.model.grid.width
        H = self.model.grid.height

        def gd(to_pos):
            return self._get_direction(my_pos, to_pos, W, H)

        all_dirs = set()
        for sp in available_spaces:
            if sp != my_pos: all_dirs.add(gd(sp))
        for x in nv_citizen_info: all_dirs.add(gd(x['position']))
        for x in pillar_info:     all_dirs.add(gd(x['position']))
        for x in police_info:     all_dirs.add(gd(x['position']))
        for x in activists_info:  all_dirs.add(gd(x['position']))

        directions = {
            d: {"can_move_to": [], "citizens": {}, "pillars": {}, "police": {}, "activists": {}}
            for d in all_dirs
        }

        for sp in available_spaces:
            if sp == my_pos: continue
            directions[gd(sp)]["can_move_to"].append(sp)

        for c in nv_citizen_info:
            d = gd(c['position'])
            if c.get('jailed', False):        cat = "jailed"
            elif c['inProtest']:              cat = "protesting"
            elif c['activeNV']:               cat = "active_nonviolent"
            elif c['grievance'] == 'high':    cat = "suffering"
            else:                             cat = "unbothered"
            directions[d]["citizens"][cat] = directions[d]["citizens"].get(cat, 0) + 1

        # Pillars — observable pressure + institution type (no private threshold info)
        # Pillars — defected or stable
        for p in pillar_info:
            d   = gd(p['position'])
            inst = p.get('institution_type', 'Unknown')
            cat  = "defected" if p['defectStatus'] else "stable"

            bucket = directions[d]["pillars"]
            if cat not in bucket:
                bucket[cat] = []
            if inst not in bucket[cat]:
                bucket[cat].append(inst)

        for p in police_info:
            d   = gd(p['position'])
            cat = "sympathetic" if p['defectStatus'] else "active"
            directions[d]["police"][cat] = directions[d]["police"].get(cat, 0) + 1

        for a in activists_info:
            d = gd(a['position'])
            if a.get('jailed', False):  cat = "jailed"
            elif a['inProtest']:        cat = "protesting"
            else:                       cat = "active_nonviolent"
            directions[d]["activists"][cat] = directions[d]["activists"].get(cat, 0) + 1

        return {"my_position": my_pos, "neighborhood": directions}

    # ── Rule NV ───────────────────────────────────────────────────────────────

    def ruleNV(self):
        neighbor_agents = self.get_visible_agents()
        nvcSum = 0
        activistSum = 0
        for neighbor in neighbor_agents:
            nvcSum += (neighbor.is_Citizen and neighbor.activeNV)
            activistSum += (neighbor.is_Activist and not neighbor.jailTerm)

        if (activistSum + nvcSum) >= self.model.const["nNVthreshold"]:
            self.inProtest      = True
            self.protestCounter = self.model.const["protestCycle"]
            self.model.logger.log_agent_event(
                self, event="protest_start", pos=self.pos,
                context={"NearbyActiveNV": activistSum + nvcSum},
            )

    # ── Rule M ────────────────────────────────────────────────────────────────

    def ruleM(self, activist_memory=None):
        grid              = self.model.grid
        activist_strategy = self.model.const["pillarproxstrat"]
        activist_radius   = (
            int(self.model.const["activistVision"])
            if activist_strategy in (2, 4)
            else int(self.model.const["vision"])
        )

        neighborhood = grid.get_neighborhood(
            pos=self.pos, moore=True, include_center=False, radius=self.model.const["vision"]
        )
        all_spaces = [cell for cell in neighborhood if grid.is_cell_empty(cell)]

        W, H = self.model.grid.width, self.model.grid.height

        def toroidal_adjust(x, y):
            dx = x - self.pos[0]; dy = y - self.pos[1]
            if dx >  W / 2: dx -= W
            elif dx < -W / 2: dx += W
            if dy >  H / 2: dy -= H
            elif dy < -H / 2: dy += H
            return (W / 2 + dx, H / 2 + dy)

        torus_adj = [toroidal_adjust(x, y) for x, y in all_spaces]
        self_adj  = (W / 2, H / 2)
        dists     = [np.linalg.norm(np.array(self_adj) - np.array(ap)) for ap in torus_adj]
        available_spaces     = [all_spaces[i] for i, d in enumerate(dists) if d <= self.model.const["vision"]]
        available_spaces.append(self.pos)
        available_spaces_adj = [torus_adj[i] for i, d in enumerate(dists) if d <= self.model.const["vision"]]
        available_spaces_adj.append(self_adj)

        neighbors_ = grid.get_neighbors(
            pos=self.pos, moore=True, include_center=False, radius=activist_radius
        )
        bigger_torus_adj = [toroidal_adjust(n.pos[0], n.pos[1]) for n in neighbors_]

        pillars_     = [neighbors_[i] for i, n in enumerate(neighbors_) if n.is_Pillar]
        pillars_adj_ = [bigger_torus_adj[i] for i, n in enumerate(neighbors_) if n.is_Pillar]

        chosen        = None
        strategy_used = None

        # ── Strategy 0: random ────────────────────────────────────────────────
        if activist_strategy == 0:
            chosen        = self.model.random.choice(available_spaces)
            strategy_used = "random"

        # ── Strategy 1: nearest pillar ────────────────────────────────────────
        if activist_strategy == 1:
            if pillars_ and available_spaces:
                min_dists = []
                for idx, sp in enumerate(available_spaces_adj):
                    pil_dists = [np.linalg.norm(np.array(sp) - np.array(p)) for p in pillars_adj_]
                    min_dists.append([min(pil_dists), available_spaces[idx]])
                chosen        = min(min_dists, key=lambda x: x[0])[1]
                strategy_used = "Nearest Pillar Normal"

        # ── Strategy 2: weakest pillar ────────────────────────────────────────
        if activist_strategy == 2:
            if pillars_ and available_spaces:
                pillar_index, target_pillar = min(
                    enumerate(pillars_), key=lambda x: x[1].defectThreshold
                )
                target_pillar_adj = pillars_adj_[pillar_index]
                min_idx, _ = min(
                    enumerate(available_spaces_adj),
                    key=lambda x: np.linalg.norm(np.array(x[1]) - np.array(target_pillar_adj))
                )
                chosen        = available_spaces[min_idx]
                strategy_used = "Weakest Pillar Extended"

        # ── Strategy 3/4: LLM-guided ──────────────────────────────────────────
        if activist_strategy in (3, 4):
            neighbor_agents_norm = self.get_visible_agents(radius=activist_radius)
            police_info, pillar_info, nv_citizen_info, activists_info = [], [], [], []

            for n in neighbor_agents_norm:
                if n.is_Police:
                    police_info.append({
                        "position":     n.pos,
                        "defectStatus": n.defect,
                    })
                if n.is_Pillar:
                    pillar_info.append({
                        "position":         n.pos,
                        "defectStatus":     n.defect,          # observable (institution stopped cooperating)
                        "institution_type": n.institution_type, # CANVAS label
                    })
                if n.is_Citizen:
                    nv_citizen_info.append({
                        "position":  n.pos,
                        "grievance": n.grievanceLevel,
                        "activeNV":  n.activeNV,
                        "inProtest": n.inProtest,
                        "jailed":    bool(n.jailTerm),
                    })
                if n.is_Activist:
                    activists_info.append({
                        "position":  n.pos,
                        "activeNV":  n.activeNV,
                        "inProtest": n.inProtest,
                        "jailed":    bool(n.jailTerm),
                    })

            # Coordination state — social network position
            free_activists = [
                {
                    "id":    n.unique_id,
                    "pos":   n.pos,
                    "state": "protesting" if n.inProtest else "active_nonviolent",
                }
                for n in neighbor_agents_norm
                if n.is_Activist and not n.jailTerm and n.unique_id != self.unique_id
            ]
            coordination_state = self._classify_coordination(len(free_activists))

            # Nearby pillar summary (observable pressure terms, no private labels)
            nearby_pillar_institutions = {
                "defected":       [],
                "stable":         [],
            }
            for p in pillar_info:
                inst = p["institution_type"]
                if p["defectStatus"]:
                    nearby_pillar_institutions["defected"].append(inst)
                else:
                    nearby_pillar_institutions["stable"].append(inst)
                

            activist_local_context = self.parse_context_by_direction(
                available_spaces=available_spaces,
                pillar_info=pillar_info,
                police_info=police_info,
                activists_info=activists_info,
                nv_citizen_info=nv_citizen_info,
            )

            # Defaults — always defined before retry loop
            chosen                 = self.pos
            # strategy_used          = "Fallback"
            target_agent           = "Unknown"
            target_pillar_inst     = "N/A"
            primary_attribute      = "Unknown"
            call_to_action         = "march"
            elapsed: float         = 0.0
            activist_response      = None
            response_tokens = "N/A"
            previous_error = None
            for attempt in range(3):
                try:
                    t0 = time.time()
                    activist_response = self.model.chat_model.ask_activist_position(
                        activist_local_context=activist_local_context,
                        activist_memory=activist_memory,
                         previous_error=previous_error,
                    )
                    elapsed = time.time() - t0
                    elapsed = f"{elapsed:.3f}s"
                    chosen_candidate = activist_response.decision.chosen_position
                    if (
                        not isinstance(chosen_candidate, list)
                        or len(chosen_candidate) != 2
                        or tuple(chosen_candidate) not in available_spaces
                    ):
                        raise ValueError(
                            f"Invalid chosen_position {chosen_candidate}. "
                            f"Must be one of {available_spaces}"
                        )
                    break

                except Exception as exc:
                    previous_error = str(exc)
                    self.model.logger.log_error(self, f"LLM attempt {attempt+1}/3 failed: {exc}")
                    activist_response = None
                    time.sleep(2 ** attempt)

            if activist_response is not None:
                d = activist_response.decision
                chosen                 = d.chosen_position
                target_agent           = d.target_agent_group
                primary_attribute    = d.primary_attribute or "Unknown"
                call_to_action    = getattr(d, "call_to_action_type", "march") or "march"
                target_pillar_inst     = getattr(d, "target_pillar_institution", "N/A")
                response_tokens = getattr(activist_response, "_response_tokens", 0) or "N/A"
            else:
                self.model.logger.log_error(
                    self, f"All 3 LLM attempts failed. Staying at {chosen}."
                )

            # Derive strategy label post-hoc from logged fields (zero LLM tokens)
            derived_strategy = derive_strategy(
                target_group=target_agent,
                institution=target_pillar_inst,
                call_to_action=call_to_action,
            )

            context_serializable = make_serializable(
                summarize_local_context(activist_local_context)
            )
            try:
                response_serializable = make_serializable(
                    activist_response.reasoning.model_dump()   
                ) if activist_response else None
            except:
                response_serializable = getattr(activist_response, "_reasoning", "N/A")
                # "ZeroShot"
                                        
            self.model.logger.log_agent_event(
                self,
                event="movement_decision",
                elapsed=elapsed,
                response_tokens=response_tokens,
                pos=tuple(chosen),
                from_pos=self.pos,
                to_pos=tuple(chosen),
                target_agent=target_agent,
                target_pillar_inst=target_pillar_inst,
                primary_attribute=primary_attribute,
                call_to_action=call_to_action,
                memory=activist_memory,
                llm_response=response_serializable,
                context={
                    **context_serializable,
                    # Social coordination
                    "coordination_state":          coordination_state,
                    "free_activists_nearby_count": len(free_activists),
                    "free_activists_nearby":       free_activists,
                    # Pillar targeting (core research variables)
                    "target_pillar_institution":   target_pillar_inst,
                    "nearby_pillar_institutions":  nearby_pillar_institutions,
                    # Tactic
                    "call_to_action_type":         call_to_action,
                    # Derived strategy (post-processing, logged here for convenience)
                    "derived_strategy":            derived_strategy,
                },
            )

        if chosen is None:
            chosen        = self.model.random.choice(available_spaces)
            strategy_used = f"Strategy {strategy_used}: Random"

        grid.move_agent(self, tuple(chosen))

    # ── Step ──────────────────────────────────────────────────────────────────

    def step(self):
        if not self.is_alive or self.model.schedule.steps < (self.delayStart + 1):
            return

        current_step    = self.model.schedule.steps
        activist_memory = self.model.retrieve_agent_cognitive_memory(
            self.unique_id, current_step
        )

        if self.jailTerm > 0:
            self.jailTerm -= 1
            self.model.logger.log_agent_event(
                self, event="jail", pos=self.pos,
                context={"jailTerm_left": self.jailTerm},
            )

        if self.protestCounter > 0:
            self.protestCounter -= 1
            if self.protestCounter <= (
                self.model.const["protestCycle"] - self.model.const["protestDuration"]
            ):
                self.inProtest = False
                if not self.jailTerm:
                    self.model.logger.log_agent_event(
                        self, event="active_nonviolent", pos=self.pos,
                        context={"StepsToEnd": self.protestCounter},
                    )

        if not self.jailTerm:
            self.ruleM(activist_memory=activist_memory)

        if not self.jailTerm and not self.protestCounter:
            self.ruleNV()

        if self.inProtest:
            self.model.protestCount += 1


# ── PoliceAgent ───────────────────────────────────────────────────────────────

class PoliceAgent(NVBaseAgent):
    def __init__(self, unique_id, agent_type, model):
        super().__init__(unique_id, agent_type, model)
        self.defect = False
        self.defectThreshold = self.model.const["defectThreshold"] + (
            self.model.random.normalvariate(0, 1) * self.model.const["defectStDev"]
        )
        self.defectThreshold = max(0.01, self.defectThreshold)
        self.defectLevel = None

    def ruleP(self):
        neighbor_agents = self.get_visible_agents()
        nNVall = len([
            a for a in neighbor_agents
            if (a.is_Activist and not a.jailTerm) or (a.is_Citizen and a.activeNV)
        ])
        nNV = len([a for a in neighbor_agents if a.inProtest])

        CanFindResistor = self.model.random.random() < self.model.const["PctFindNVResistor"]
        CanTargetNV     = self.model.random.random() < self.model.const["PctTargetNV"]

        if nNVall and CanTargetNV and (CanFindResistor or nNV):
            NVNeighbors = (
                [a for a in neighbor_agents if a.inProtest]
                if nNV
                else [a for a in neighbor_agents if (a.is_Activist and not a.jailTerm) or (a.is_Citizen and a.activeNV)]
            )
            NVTarget = self.model.random.choice(NVNeighbors)
            KillNV   = self.model.random.random() < self.model.const["PctKillNV"]

            if KillNV:
                KillPos = NVTarget.pos
                NVTarget.is_alive = False
                if NVTarget.is_Citizen: NVTarget.activeNV = False
                self.model.grid.remove_agent(NVTarget)
                self.model.schedule.remove(NVTarget)
                self.model.governmentLegitimacy *= self.model.const["BackfireCoeff"]
                self.model.logger.log_agent_event(
                    self, event="kill", pos=self.pos,
                    target_agent=NVTarget.type.name,
                    context={"target_id": NVTarget.unique_id,
                             "target_pos": str(KillPos),
                             "target_type": NVTarget.type.name},
                )
            else:
                NVTarget.jailTerm  = self.random.randint(1, self.model.const["MaxJailTerm"] - 1)
                NVTarget.inProtest = False
                if NVTarget.is_Citizen: NVTarget.activeNV = False
                self.model.logger.log_agent_event(
                    self, event="jail", pos=self.pos,
                    target_agent=NVTarget.type.name,
                    context={"target_id": NVTarget.unique_id,
                             "target_pos": str(NVTarget.pos),
                             "target_type": NVTarget.type.name,
                             "jail_term": NVTarget.jailTerm},
                )

    def ruleD(self):
        """Chenoweth Rule D — unchanged."""
        neighbor_agents = self.get_visible_agents()
        activistSum, nvcSum, nvCitizen, policeSum = (0, 0, 0, 0)
        for neighbor in neighbor_agents:
            activistSum += (neighbor.is_Activist and neighbor.inProtest) 
            nvcSum += (neighbor.is_Citizen and neighbor.inProtest) 
            nvCitizen += (neighbor.is_Citizen and neighbor.activeNV and not neighbor.inProtest) 
            policeSum += (neighbor.is_Police and not neighbor.defect)

        total_agents = len(neighbor_agents)
        active_protestors = activistSum + nvcSum
        ratio = active_protestors / total_agents if total_agents > 0 else 0

        # Defection condition
        if active_protestors > total_agents * self.defectThreshold:
            self.defect = True
            self.model.logger.log_agent_event(
                self, event="defect", pos=self.pos,
                context={"protesters_seen":  active_protestors,
                         "total_agents":     total_agents,
                         "defect_threshold": round(self.defectThreshold, 4),
                         "defect_ratio":      round(ratio, 4),
                },
            )

    def step(self):
        if not self.is_alive or self.model.schedule.steps < (self.delayStart + 1):
            return
        self.ruleM()
        if not self.defect:
            self.ruleP()
        self.ruleD()

