"""
agent_based.py

Changes from previous version
------------------------------
OBSERVABLE PRESSURE REPLACES INTERNAL THRESHOLD LABEL
  Previously parse_context_by_direction categorised pillars as "wavering" or
  "loyal" derived from defectLevel, which in turn comes from the internal
  defectThreshold (a private parameter no real activist can observe).

  Now: _compute_observable_pressure() counts visible protesters within radius 2
  of each pillar position, using only agents the activist can already see.
  Labels: "under_pressure" (ratio > 0.30), "stirring" (ratio > 0.10), "stable".

  This is epistemically honest — it models what a real activist would observe
  (visible crowd density around an institution) rather than what only a
  simulation researcher can read (the institution's private loyalty threshold).

  Research implication: the LLM activist now decides which institution to
  approach based on visible social signals, not leaked threshold information.
  This directly tests Chenoweth's Strategy 2 through an honest mechanism.

DERIVE_STRATEGY (post-processing, not LLM output)
  derive_strategy(target_group, institution, call_to_action) → strategy label.
  Computed deterministically from logged fields.  Never sent to or from LLM.
  Six categories: solidarity_building, citizen_mobilisation,
  security_force_conversion, economic_disruption, regime_delegitimisation,
  moral_witness, pillar_persuasion.

PILLAR INFO DICT CHANGE
  Removed: defectLevel (internal, private)
  Added:   pressure (observable: under_pressure / stirring / stable)
  Kept:    institution_type, defectStatus, position

NEARBY_PILLAR_INSTITUTIONS LOG FIELD
  Keys updated from wavering/loyal to under_pressure/stirring/stable/defected.
  All terms now refer to observable social signals only.
"""

